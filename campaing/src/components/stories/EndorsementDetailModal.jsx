const EndorsementDetailModal = ({
  isOpen,
  onClose,
  endorsements = [],
  initialIndex = 0,
  currentUser,
  onCommentsUpdate,
}) => {
  const [currentIndex, setCurrentIndex] = useState(initialIndex);
  const [progress, setProgress] = useState(0);
  const [isPaused, setIsPaused] = useState(false);
  const [showComments, setShowComments] = useState(false);
  const [likesState, setLikesState] = useState({});
  const [likesCountState, setLikesCountState] = useState({});
  const [commentsState, setCommentsState] = useState({});
  const [commentsLoading, setCommentsLoading] = useState({});
  const [newComment, setNewComment] = useState("");
  const [isSubmitting, setIsSubmitting] = useState(false);
  const [isMuted, setIsMuted] = useState(true);
  const [touchStart, setTouchStart] = useState(null);

  const timerRef = useRef(null);
  const videoRef = useRef(null);
  const STORY_DURATION = 5000;

  const current = endorsements[currentIndex];

  const loadComments = useCallback(async (storyId) => {
    if (!storyId) return;
    setCommentsLoading((prev) => ({ ...prev, [storyId]: true }));
    try {
      const response = await api.get(`/endorsements/${storyId}/comments?t=${Date.now()}`);
      let comments = [];
      if (response.data?.data?.comments) {
        comments = response.data.data.comments;
      } else if (response.data?.comments) {
        comments = response.data.comments;
      } else if (Array.isArray(response.data?.data)) {
        comments = response.data.data;
      } else if (Array.isArray(response.data)) {
        comments = response.data;
      }
      setCommentsState((prev) => ({ ...prev, [storyId]: comments }));
    } catch (error) {
      setCommentsState((prev) => ({ ...prev, [storyId]: [] }));
    } finally {
      setCommentsLoading((prev) => ({ ...prev, [storyId]: false }));
    }
  }, []);

  useEffect(() => {
    if (isOpen && current?.id) {
      loadComments(current.id);
      if (current.likes !== undefined && likesCountState[current.id] === undefined) {
        setLikesCountState((prev) => ({
          ...prev,
          [current.id]: current.likes || 0,
        }));
      }
    }
  }, [isOpen, current?.id, loadComments, current?.likes]);

  const getAvatarUrl = (item) => {
    // image_url is the story MEDIA, not the user's profile picture
    // Always use a generated avatar based on the user's name
    return `https://ui-avatars.com/api/?name=${encodeURIComponent(item?.user_name || "User")}&background=22c55e&color=fff&size=100`;
  };

  const getMediaUrl = (item) => {
    if (item?.image_url) {
      return buildImageUrl(item.image_url);
    }
    return null;
  };

  const formatDate = (dateString) => {
    if (!dateString) return "Recently";
    const date = new Date(dateString);
    const now = new Date();
    const diffMins = Math.floor((now - date) / 60000);
    const diffHours = Math.floor(diffMins / 60);
    const diffDays = Math.floor(diffHours / 24);

    if (diffMins < 1) return "Just now";
    if (diffMins < 60) return `${diffMins}m ago`;
    if (diffHours < 24) return `${diffHours}h ago`;
    if (diffDays < 7) return `${diffDays}d ago`;
    return date.toLocaleDateString();
  };

  const capitalizeFirst = (str) => {
    if (!str) return "";
    return str.charAt(0).toUpperCase() + str.slice(1).toLowerCase();
  };

  useEffect(() => {
    if (isOpen) {
      setCurrentIndex(initialIndex);
      setProgress(0);
      setIsPaused(false);
    }
  }, [isOpen, initialIndex]);

  const handleNext = useCallback(() => {
    if (currentIndex < endorsements.length - 1) {
      setCurrentIndex((prev) => prev + 1);
      setProgress(0);
    } else {
      onClose();
    }
  }, [currentIndex, endorsements.length, onClose]);

  const handlePrev = useCallback(() => {
    if (currentIndex > 0) {
      setCurrentIndex((prev) => prev - 1);
      setProgress(0);
    }
  }, [currentIndex]);

  const handleTouchStart = (e) => {
    setTouchStart(e.touches[0].clientX);
  };

  const handleTouchEnd = (e) => {
    if (!touchStart) return;
    const touchEnd = e.changedTouches[0].clientX;
    const diff = touchStart - touchEnd;

    if (Math.abs(diff) > 50) {
      if (diff > 0) {
        handleNext();
      } else {
        handlePrev();
      }
    }
    setTouchStart(null);
  };

  useEffect(() => {
    if (!isOpen || isPaused || showComments) return;

    const interval = 100;
    const step = 100 / (STORY_DURATION / interval);

    timerRef.current = setInterval(() => {
      setProgress((prev) => {
        if (prev >= 100) {
          handleNext();
          return 0;
        }
        return prev + step;
      });
    }, interval);

    return () => clearInterval(timerRef.current);
  }, [isOpen, isPaused, showComments, handleNext]);

  const handleLike = async () => {
    if (!current) return;
    const storyId = current.id;
    const isLiked = likesState[storyId];
    const currentLikes = likesCountState[storyId] || current.likes || 0;

    setLikesState((prev) => ({ ...prev, [storyId]: !isLiked }));
    setLikesCountState((prev) => ({
      ...prev,
      [storyId]: isLiked ? currentLikes - 1 : currentLikes + 1,
    }));

    try {
      const response = await api.post(`/endorsements/${storyId}/like`, {
        user_id: currentUser?.id || "anonymous"
      });
      if (response.success) {
        setLikesState((prev) => ({ ...prev, [storyId]: response.liked }));
        setLikesCountState((prev) => ({
          ...prev,
          [storyId]: response.likes,
        }));
      }
    } catch (e) {
      setLikesState((prev) => ({ ...prev, [storyId]: isLiked }));
      setLikesCountState((prev) => ({ ...prev, [storyId]: currentLikes }));
    }
  };

  const handleSendComment = async () => {
    if (!current || !newComment.trim() || isSubmitting) return;

    const storyId = current.id;
    const tempId = `temp_${Date.now()}`;

    setIsSubmitting(true);

    const newCommentObj = {
      id: tempId,
      user_id: currentUser?.id || "anonymous",
      user_name: currentUser?.name || "Anonymous",
      comment: newComment.trim(),
      created_at: new Date().toISOString(),
      likes: 0,
      liked: false,
    };

    setCommentsState((prev) => ({
      ...prev,
      [storyId]: [...(prev[storyId] || []), newCommentObj],
    }));

    setNewComment("");

    try {
      const response = await api.post(`/endorsements/${storyId}/comments`, {
        user_id: currentUser?.id || "anonymous",
        user_name: currentUser?.name || "Anonymous",
        comment: newComment.trim(),
      });

      if (response.success && response.data) {
        setCommentsState((prev) => ({
          ...prev,
          [storyId]: prev[storyId].map((c) =>
            c.id === tempId ? response.data : c
          ),
        }));
      } else {
        setCommentsState((prev) => ({
          ...prev,
          [storyId]: prev[storyId].filter((c) => c.id !== tempId),
        }));
      }
    } catch (error) {
      setCommentsState((prev) => ({
        ...prev,
        [storyId]: prev[storyId].filter((c) => c.id !== tempId),
      }));
    } finally {
      setIsSubmitting(false);
    }
  };

  const handleLikeComment = async (commentId) => {
    if (!current) return;

    try {
      const response = await api.post(`/endorsements/${current.id}/comments/${commentId}/like`, {
        user_id: currentUser?.id || "anonymous"
      });

      if (response.success) {
        setCommentsState((prev) => ({
          ...prev,
          [current.id]: prev[current.id].map((c) =>
            c.id === commentId
              ? { ...c, liked: response.liked, likes: response.likes }
              : c
          ),
        }));
      }
    } catch (error) {
      // Silent fail
    }
  };

  const handleKeyPress = (e) => {
    if (e.key === "Enter" && !e.shiftKey) {
      e.preventDefault();
      handleSendComment();
    }
  };

  const handlePause = () => setIsPaused(true);
  const handleResume = () => setIsPaused(false);

  if (!isOpen || !current) return null;

  const currentLikesCount = likesCountState[current.id] !== undefined
    ? likesCountState[current.id]
    : current.likes || 0;

  const currentCommentsCount = commentsState[current.id]?.length || 0;
  const mediaUrl = getMediaUrl(current);
  const hasMedia = mediaUrl && (current.media_type === "image" || current.media_type === "video");
  const isVideo = hasMedia && current.media_type === "video";
  const displayMessage = getDisplayMessage(current);

  return (
    <>
      <FullScreenOverlay
        onTouchStart={handleTouchStart}
        onTouchEnd={handleTouchEnd}
      >
        <ProgressContainer>
          {endorsements.map((_, idx) => (
            <ProgressTrack key={idx}>
              <ProgressFill
                $active={idx === currentIndex}
                $width={idx < currentIndex ? 100 : idx === currentIndex ? progress : 0}
              />
            </ProgressTrack>
          ))}
        </ProgressContainer>

        <StoryHeader>
          <UserInfo>
            <UserAvatar src={getAvatarUrl(current)} alt={current.user_name} />
            <UserTextInfo>
              <UserName>{capitalizeFirst(current.user_name || "Anonymous")}</UserName>
              <UserDetail>
                <Clock size={10} />
                <span>{formatDate(current.created_at)}</span>
              </UserDetail>
            </UserTextInfo>
          </UserInfo>
          <CloseBtn onClick={onClose}>
            <X size={24} />
          </CloseBtn>
        </StoryHeader>

        <LeftZone onClick={handlePrev} onMouseEnter={handlePause} onMouseLeave={handleResume} />
        <RightZone onClick={handleNext} onMouseEnter={handlePause} onMouseLeave={handleResume} />

        {hasMedia ? (
          <>
            <FullScreenMedia onClick={handlePause}>
              {isVideo ? (
                <video
                  ref={videoRef}
                  src={mediaUrl}
                  autoPlay
                  loop
                  playsInline
                  muted={isMuted}
                />
              ) : (
                <img src={mediaUrl} alt="Story" />
              )}
            </FullScreenMedia>
            <GradientOverlay />

            {isVideo && (
              <VolumeButton onClick={() => setIsMuted(!isMuted)}>
                {isMuted ? <VolumeX size={18} /> : <Volume2 size={18} />}
              </VolumeButton>
            )}
          </>
        ) : null}

        {displayMessage && hasMedia && (
          <BottomMessage>
            <MessageText>{displayMessage}</MessageText>
          </BottomMessage>
        )}

        {displayMessage && !hasMedia && (
          <CenteredMessageContainer>
            <CenteredText>{displayMessage}</CenteredText>
          </CenteredMessageContainer>
        )}

        <EndorsementMeta>
          <MetaItem>
            <Heart size={14} />
            <span>{currentLikesCount}</span>
          </MetaItem>
          <MetaItem>
            <MessageCircle size={14} />
            <span>{currentCommentsCount}</span>
          </MetaItem>
        </EndorsementMeta>

        <RightActions>
          <ActionButton onClick={handleLike} onMouseEnter={handlePause} onMouseLeave={handleResume}>
            <Heart
              size={22}
              fill={likesState[current.id] ? "#ef4444" : "none"}
              color={likesState[current.id] ? "#ef4444" : "white"}
            />
            <span>Like</span>
            <CountSpan>{currentLikesCount}</CountSpan>
          </ActionButton>

          <ActionButton onClick={() => setShowComments(true)} onMouseEnter={handlePause} onMouseLeave={handleResume}>
            <MessageCircle size={22} />
            <span>Chat</span>
            <CountSpan>{currentCommentsCount}</CountSpan>
          </ActionButton>

          <ActionButton onMouseEnter={handlePause} onMouseLeave={handleResume}>
            <TrendingUp size={22} color="#fbbf24" />
            <span>Boost</span>
            <CountSpan>{current.boost_count || 0}</CountSpan>
          </ActionButton>
        </RightActions>

        {showComments && (
          <CommentsModalOverlay>
            <CommentsModalHeader>
              <div style={{ color: "white", fontWeight: "bold", fontSize: "1rem" }}>
                Comments ({currentCommentsCount})
              </div>
              <CloseBtn onClick={() => setShowComments(false)}>
                <X size={20} />
              </CloseBtn>
            </CommentsModalHeader>

            <CommentsList>
              {commentsLoading[current.id] ? (
                <div style={{ padding: "40px", textAlign: "center", color: "white" }}>
                  Loading comments...
                </div>
              ) : commentsState[current.id]?.length === 0 ? (
                <EmptyComments>No comments yet. Be the first to comment!</EmptyComments>
              ) : (
                commentsState[current.id]?.map((comment) => (
                  <CommentItem key={comment.id}>
                    <CommentAvatar>
                      {comment.user_name?.charAt(0).toUpperCase() || "U"}
                    </CommentAvatar>
                    <CommentContent>
                      <CommentHeader>
                        <CommentUserName>{comment.user_name || "Anonymous"}</CommentUserName>
                        <CommentTime>{formatDate(comment.created_at)}</CommentTime>
                      </CommentHeader>
                      <CommentText>{comment.comment}</CommentText>
                      <CommentActions>
                        <LikeButton
                          $liked={comment.liked}
                          onClick={() => handleLikeComment(comment.id)}
                        >
                          <Heart size={14} fill={comment.liked ? "#ef4444" : "none"} />
                          <span>{comment.likes || 0}</span>
                        </LikeButton>
                      </CommentActions>
                    </CommentContent>
                  </CommentItem>
                ))
              )}
            </CommentsList>

            <CommentInputWrapper>
              <InputForm onSubmit={(e) => { e.preventDefault(); handleSendComment(); }}>
                <CommentInput
                  placeholder="Write a comment..."
                  value={newComment}
                  onChange={(e) => setNewComment(e.target.value)}
                  onKeyPress={handleKeyPress}
                  rows={1}
                />
                <SendButton type="submit" disabled={!newComment.trim() || isSubmitting}>
                  <Send size={18} color="white" />
                </SendButton>
              </InputForm>
            </CommentInputWrapper>
          </CommentsModalOverlay>
        )}
      </FullScreenOverlay>
    </>
  );
};

export default EndorsementDetailModal;