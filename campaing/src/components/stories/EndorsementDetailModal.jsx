// Check if message is auto-generated
const isAutoGeneratedMessage = (message, mediaType) => {
  if (!message) return true;
  const autoMessages = [
    "📷 Photo", "📹 Video", "💬 Support message", "Support message",
    "Photo", "Video", "📸 Photo", "🎥 Video"
  ];
  if ((mediaType === "image" || mediaType === "video") && autoMessages.includes(message.trim())) {
    return true;
  }
  return false;
};

// Get display message (only real user messages)
const getDisplayMessage = (story) => {
  const { message, media_type } = story;
  if (message && !isAutoGeneratedMessage(message, media_type)) {
    return message;
  }
  return null;
};

